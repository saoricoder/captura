  function normalizeKey(value) {
    return String(value || '').replace(/\s+/g, ' ').trim().toLowerCase();
  }

  function translateLocal(text) {
    const sample = String(text || '').replace(/\s+/g, ' ').trim();
    if (!sample) return null;

    const direct = EN_ES[normalizeKey(sample)];
    if (direct) return direct;

    const words = normalizeKey(sample).split(' ');
    if (words.length > 1) {
      const translated = words.map((word) => EN_ES[word] || word);
      if (translated.some((word, index) => word !== words[index])) {
        return translated.join(' ');
      }
    }

    return null;
  }

